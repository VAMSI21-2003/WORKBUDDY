"""A snapshot of every string the page writes (frontend design 4.3, item 11).

The page's copy lives in its templates, its stylesheet and its script. This test pulls out every
string those can put on screen or hand to a screen reader, and compares the sorted list with
``tests/web/ui_copy_snapshot.txt``. A new or changed sentence is a diff in that file, which the
independent reviewer reads and signs off in the review file. After a deliberate change:
``python -m pytest tests/web/test_copy_snapshot.py --update-ui-copy`` and commit the new file.

What is collected:

- every text node of every template (a template's own ``{{ value }}`` becomes ``{value}``, and a
  call to a copy macro disappears, because the macro's own text is collected where it is written);
- the attributes ``title``, ``aria-label``, ``placeholder`` and ``alt``, ``value`` on a button, and
  ``content`` on a ``<meta>``;
- the ``content:`` values in ``styles.css`` and every quoted string literal in ``app.js``.
"""

from __future__ import annotations

import difflib
import re
from html.parser import HTMLParser
from pathlib import Path

import pytest

from backend.web.templating import STATIC_DIR, TEMPLATES_DIR

SNAPSHOT = Path(__file__).with_name("ui_copy_snapshot.txt")
HEADER = [
    "# Every string the page writes: template text, labelled attributes, CSS content, script",
    "# literals. Generated by tests/web/test_copy_snapshot.py; regenerate with --update-ui-copy.",
    "# A change here is a change to what the page says: read it as one.",
]
ATTRIBUTES = {"title", "aria-label", "placeholder", "alt"}


class _Collector(HTMLParser):
    def __init__(self, source: str) -> None:
        super().__init__(convert_charrefs=True)
        self.source = source
        self.found: set[str] = set()
        self._skip = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag in {"script", "style"}:
            self._skip += 1
        for name, value in attrs:
            text = " ".join((value or "").split())
            if not text:
                continue
            if (
                name in ATTRIBUTES
                or (name == "value" and tag == "button")
                or (name == "content" and tag == "meta")
            ):
                self.found.add(f"{self.source} attr:{name}: {text}")

    def handle_endtag(self, tag: str) -> None:
        if tag in {"script", "style"}:
            self._skip = max(0, self._skip - 1)

    def handle_data(self, data: str) -> None:
        text = " ".join(data.replace("<j-x/>", " ").split())
        if text and not self._skip:
            self.found.add(f"{self.source} text: {text}")


_TAG = re.compile(r"<[a-zA-Z](?:[^<>]|\{%.*?%\}|\{\{.*?\}\})*>", re.DOTALL)
_COPY_CALL = r"\{\{-?\s*copy\.[^}]*?-?\}\}"
_ONLY_MACRO_CALLS = re.compile(r"^(\{[\w.]+\(.*?\)\}\s*)+$")


def _template_strings(path: Path) -> set[str]:
    source = path.read_text(encoding="utf-8")
    source = re.sub(r"\{#.*?#\}", "", source, flags=re.DOTALL)

    def inside_tag(match: re.Match[str]) -> str:
        tag = re.sub(r"\{%.*?%\}", " ", match.group(0), flags=re.DOTALL)
        return re.sub(_COPY_CALL, "", tag)

    source = _TAG.sub(inside_tag, source)
    source = re.sub(_COPY_CALL, "<j-x/>", source)
    source = re.sub(r"\{\{-?\s*(.*?)\s*-?\}\}", lambda m: "{" + m.group(1) + "}", source)
    source = re.sub(r"\{%.*?%\}", "<j-x/>", source, flags=re.DOTALL)
    collector = _Collector(path.name)
    collector.feed(source)
    collector.close()
    # A node that is only calls to other macros says nothing itself.
    return {line for line in collector.found if not _ONLY_MACRO_CALLS.match(line.split(": ", 1)[1])}


def _script_strings(path: Path) -> set[str]:
    source = path.read_text(encoding="utf-8")
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.DOTALL)
    source = re.sub(r"(?m)^\s*//.*$", "", source)
    literal = re.compile(r"'(?:\\.|[^'\\\n])*'|\"(?:\\.|[^\"\\\n])*\"|`(?:\\.|[^`\\])*`")
    return {
        f"{path.name} string: {m.group(0)[1:-1]}"
        for m in literal.finditer(source)
        if m.group(0)[1:-1]
    }


def _css_strings(path: Path) -> set[str]:
    css = path.read_text(encoding="utf-8")
    found = re.findall(r"content\s*:\s*(\"[^\"]*\"|'[^']*')", css)
    return {f"{path.name} content: {value[1:-1]}" for value in found if value[1:-1]}


def collect() -> list[str]:
    found: set[str] = set()
    for template in sorted(TEMPLATES_DIR.glob("*.html")):
        found |= _template_strings(template)
    found |= _script_strings(STATIC_DIR / "app.js")
    found |= _css_strings(STATIC_DIR / "styles.css")
    return sorted(found)


def render_snapshot() -> str:
    return "\n".join([*HEADER, *collect()]) + "\n"


def test_the_pages_copy_matches_the_committed_snapshot(request: pytest.FixtureRequest) -> None:
    current = render_snapshot()
    if request.config.getoption("--update-ui-copy"):
        SNAPSHOT.write_text(current, encoding="utf-8")
        return
    assert SNAPSHOT.exists(), "run with --update-ui-copy to create tests/web/ui_copy_snapshot.txt"
    committed = SNAPSHOT.read_text(encoding="utf-8")
    if committed != current:
        diff = "\n".join(
            difflib.unified_diff(
                committed.splitlines(), current.splitlines(), "committed", "current", lineterm=""
            )
        )
        pytest.fail(
            "The page's copy changed. If that is intended, regenerate the snapshot with\n"
            "  python -m pytest tests/web/test_copy_snapshot.py --update-ui-copy\n"
            "and commit it; the reviewer reads the diff.\n" + diff
        )


def test_the_snapshot_catches_a_sentence_added_to_a_template(tmp_path: Path) -> None:
    template = tmp_path / "x.html"
    template.write_text("<p>Hello {{ name }}.</p><p>All set!</p>", encoding="utf-8")
    assert "x.html text: All set!" in _template_strings(template)
    assert "x.html text: Hello {name}." in _template_strings(template)


def test_the_collector_reads_script_literals_but_not_comments() -> None:
    script = STATIC_DIR / "app.js"
    found = _script_strings(script)
    assert any("lost-contact" in line for line in found)
    assert not any("isn't" in line and "string:" in line and "//" in line for line in found)
